begin;
select set_config('alive.internal','yes',true);
do $$
declare rc text:='__REVIEW_QA__'; h text:=md5('review_host')::uuid::text; a text:=md5('review_a')::uuid::text; b text:=md5('review_b')::uuid::text;
 g bigint; before_ jsonb; report jsonb; m jsonb; rev bigint;
begin
 insert into public.rooms(code,host_id,scenario_id,card_mode,phase,settings) values(rc,h,'MEDIEVAL_PLAGUE_QUEEN','random','lobby','{"min_players":2,"target_survivors":2}');
 insert into public.players(id,name,room_code,is_ready,seat_number) values(h,'Host',rc,true,1),(a,'A',rc,true,2),(b,'B',rc,true,3);
 perform set_config('request.jwt.claim.sub',h,true);
 perform public.alive_start(rc);
 update public.rooms set countdown_ends_at=now()-interval '1 second' where code=rc;
 perform alive_private.start_game(rc,true);
 report:=public.alive_review_export(rc);before_:=report->'start';
 if before_->>'phase' is distinct from 'reveal' or jsonb_array_length(before_->'players')<>2 or jsonb_array_length(before_->'routes')<>2 or before_->'story' is null then raise exception 'Incomplete opening snapshot %',before_;end if;
 select id into strict g from public.player_cards where room_code=rc and player_id=a and category='goal';
 update public.player_cards set text='Discuss a plan',effect_params='{"goal_kind":"discussion"}' where id=g;
 perform set_config('request.jwt.claim.sub',b,true);
 begin perform public.alive_review_export(rc);raise exception 'Foreign export' using errcode='XX000';exception when raise_exception then null;end;
 begin perform public.alive_mark_goal(rc,g,true);raise exception 'Marked foreign goal' using errcode='XX000';exception when raise_exception then null;end;
 perform set_config('request.jwt.claim.sub',a,true);
 perform public.alive_mark_goal(rc,g,true);
 m:=public.alive_goal_review(rc)->0;
 if m->>'met' is distinct from 'true' or m->>'source' is distinct from 'игрок' or jsonb_array_length(public.alive_goal_review(rc))<>1 then raise exception 'Self mark %',m;end if;
 perform set_config('request.jwt.claim.sub',h,true);
 perform public.alive_mark_goal(rc,g,false);
 update public.room_resources set amount=2 where room_code=rc and key='water_liters';
 select revision into rev from public.rooms where code=rc;
 perform public.alive_timer(rc,'start',5,rev);
 select revision into rev from public.rooms where code=rc;
 perform public.alive_timer(rc,'adjust',-15,rev);
 if exists(select 1 from public.rooms where code=rc and (phase_running or phase_ends_at is not null)) then raise exception 'Invalid zero timer';end if;
 update public.rooms set current_phase='finished',verdict='defeat' where code=rc;
 report:=public.alive_review_export(rc);
 if before_ is distinct from report->'start' or not (report->'current'->'resources' @> '[{"amount":2}]') then raise exception 'Snapshot drift';end if;
 if not (report ? 'effects_played' and report ? 'effect_requests') then raise exception 'Missing effect evidence';end if;
 select value into strict m from jsonb_array_elements(report->'current'->'goals') where (value->>'id')::bigint=g;
 if m->>'met' is distinct from 'false' or m->>'self_met' is distinct from 'true' or m->>'source' is distinct from 'ведущий' then raise exception 'Override %',m;end if;
 begin perform public.alive_mark_goal(rc,g,true);raise exception 'Edited finished goal' using errcode='XX000';exception when raise_exception then null;end;
 update public.rooms set phase='lobby' where code=rc;
 if exists(select 1 from alive_private.review_starts where room_code=rc) then raise exception 'Stale start';end if;
end $$;
select 'Opening snapshot, export privacy, goal marks, verdict lock, timer and reset passed' result;
rollback;
